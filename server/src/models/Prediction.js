// ──────────────────────────────────────────────────────────
// FanSync — Prediction Schema
// ──────────────────────────────────────────────────────────
// Tracks individual user predictions/votes on AI-generated polls.
// Points are only awarded after the poll is resolved (i.e., the
// actual match event confirms the outcome). Streak bonuses
// multiply the base points for consecutive correct predictions.
// ──────────────────────────────────────────────────────────

import mongoose from 'mongoose';

const predictionSchema = new mongoose.Schema(
  {
    // Reference to the User who made this prediction
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },

    // Unique poll identifier (generated by the AI agent)
    pollId: {
      type: String,
      required: true,
      index: true,
    },

    // The option the user selected (e.g., "Yes", "No", "4 runs")
    selectedOption: {
      type: String,
      required: true,
    },

    // Points awarded after resolution (0 if incorrect, base * streak multiplier if correct)
    pointsAwarded: {
      type: Number,
      default: 0,
    },

    // Whether this prediction has been resolved against the actual outcome
    isResolved: {
      type: Boolean,
      default: false,
    },

    // Whether the prediction was correct (null until resolved)
    isCorrect: {
      type: Boolean,
      default: null,
    },

    // The actual outcome after resolution
    actualOutcome: {
      type: String,
      default: null,
    },

    // Timestamp when the vote was placed
    votedAt: {
      type: Date,
      default: Date.now,
    },

    // Timestamp when the prediction was resolved
    resolvedAt: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
  }
);

// Compound index: fast lookup of a user's vote on a specific poll
predictionSchema.index({ userId: 1, pollId: 1 }, { unique: true });

// Index for resolving all votes on a poll at once
predictionSchema.index({ pollId: 1, isResolved: 1 });

const Prediction = mongoose.model('Prediction', predictionSchema);
export default Prediction;
